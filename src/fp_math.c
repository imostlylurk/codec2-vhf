uint32_t fp_isqrt64(uint64_t v)
{
    uint64_t res = 0;

    if (v == 0)
        return 0;

    /* start at the largest 4^k <= v, derived from CLZ instead of the
       previous 62->0 down-shift walk (bit-identical start bit) */
    uint64_t bit = 1ULL << ((63 - __builtin_clzll(v)) & ~1ULL);

    while (bit) {
		if (v >= res + bit) {
			v -= res + bit;
			res = (res >> 1) + bit;
		} else {
			res >>= 1;
		}
		bit >>= 2;
	}
	return (uint32_t)res;
}

/* ------------------------------------------------------------------ */
/* log2: leading-zero position + 64-entry fraction table              */
/* ------------------------------------------------------------------ */

static inline int fp_msb64(uint64_t v)
{
    /* CLZ formulation is bit-identical to the previous normalisation
       walk and removes up to ~60 loop iterations per log2 call (a
       top M4 decode cost). */
    return v ? 63 - __builtin_clzll(v) : 0;
}

int32_t fp_log2_q16(int64_t vv)
{
	uint64_t v = (uint64_t)vv;
	int msb = fp_msb64(v);
	/* normalise mantissa to [2^62, 2^63): v/2^msb in [1,2) */
	uint64_t m = v << (62 - msb);
	uint32_t j = (uint32_t)(m >> 56) - 64; /* top 7 bits -> 0..63 */
	uint32_t frac = (uint32_t)(m >> 40) & 0xFFFF;
	int32_t a = fp_log2_tab[j];
	int32_t d = fp_log2_tab[j + 1] - a;

	return (msb << 16) + a + (int32_t)(((int64_t)d * frac) >> 16);
}

/* ------------------------------------------------------------------ */
/* exp2: integer part as shift, fraction via 64-entry table           */
/* ------------------------------------------------------------------ */

int64_t fp_exp2_q31(int32_t x)
{
	int32_t xi = x >> 16;                  /* arithmetic shift, floor */
	uint32_t f = (uint32_t)(x - xi * 65536);
	uint32_t j = f >> 10;                  /* 0..63 */
	uint32_t frac = f & 0x3FF;
	int32_t a = fp_exp2_tab[j];
	int32_t d = fp_exp2_tab[j + 1] - a;
	int64_t mant = a + (int32_t)(((int64_t)d * frac) >> 10);

	/* table holds 2^(f-1); multiply back by two */
	if (xi >= 0)
		return mant << (xi + 1);
	int32_t sh = -xi - 1;
	if (sh == 0)
		return mant;
	/* round the final down-shift to half an LSB of the result */
	return (mant + (1LL << (sh - 1))) >> sh;
}
