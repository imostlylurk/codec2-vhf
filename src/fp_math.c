static inline int32_t fp_sin_lerp(uint32_t p)
{
	/* p: position within one quadrant, 2^30 == pi/2.  Mirrored-quadrant
	   callers pass 2^30 - p, which is exactly 2^30 at p == 0: that is
	   sin(pi/2) == 1.0, i.e. the final table entry (frac is 0 there). */
	if (p >= 0x40000000u)
		return fp_sin_tab[1024];
	uint32_t idx = p >> 20;                /* 0..1023 */
	uint32_t frac = p & 0xFFFFF;           /* 20 fractional bits */
	int32_t a = fp_sin_tab[idx];
	int32_t d = fp_sin_tab[idx + 1] - a;
	return a + (int32_t)(((int64_t)d * frac) >> 20);
}

int32_t fp_sin_q31(uint32_t phase)
{
	uint32_t q = phase >> 30;              /* quadrant */
	uint32_t p = phase & 0x3FFFFFFFu;      /* position in quadrant */

	switch (q) {
	case 0:
		return fp_sin_lerp(p);
	case 1:
		return fp_sin_lerp(0x40000000u - p);
	case 2:
		return -fp_sin_lerp(p);
	default:
		return -fp_sin_lerp(0x40000000u - p);
	}
}

void fp_sincos_q31(uint32_t phase, int32_t *s, int32_t *c)
{
	uint32_t q = phase >> 30;
	uint32_t p = phase & 0x3FFFFFFFu;

	/* cos(x) = sin(pi/2 - x): one quadrant ahead */
	switch (q) {
	case 0:
		*s = fp_sin_lerp(p);
		*c = fp_sin_lerp(0x40000000u - p);
		break;
	case 1:
		*s = fp_sin_lerp(0x40000000u - p);
		*c = -fp_sin_lerp(p);
		break;
	case 2:
		*s = -fp_sin_lerp(p);
		*c = -fp_sin_lerp(0x40000000u - p);
		break;
	default:
		*s = -fp_sin_lerp(0x40000000u - p);
		*c = fp_sin_lerp(p);
		break;
	}
}

