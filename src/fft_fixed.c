/*
  In-place iterative radix-2 DIT complex FFT of FFT_FIXED_N points.
  sign = -1: forward (e^{-j...}), sign = +1: inverse (e^{+j...}).
  Unscaled in both directions; every intermediate value stays within
  sum(|x|) of the input sequence.

  The butterfly is instantiated twice via BUTTERFLY_STAGE(NEG) so the
  twiddle imaginary sign is a compile-time constant: a runtime select
  here cost ~5 instructions + 2 stack round-trips per butterfly (the
  dominant M4 decode cost).  The NEG instantiation must stay in this
  file (not a shared inline) or -Os stops folding it.
*/
#define BUTTERFLY_STAGE(NEG)                                                   \
    do {                                                                       \
        for (uint32_t base = 0; base < FFT_FIXED_N; base += len) {             \
            for (uint32_t j = 0; j < half; j++) {                              \
                uint32_t ti = j * tstep;                                       \
                int32_t wr = fft_tw_cos[ti];                                   \
                int32_t wi = NEG ? -fft_tw_sin[ti] : fft_tw_sin[ti];           \
                int32_t ar = x[base + j + half].r;                             \
                int32_t ai = x[base + j + half].i;                             \
                int32_t tr = (int32_t)(((int64_t)ar * wr                       \
                                        - (int64_t)ai * wi) >> 31);            \
                int32_t ti_ = (int32_t)(((int64_t)ar * wi                      \
                                         + (int64_t)ai * wr) >> 31);           \
                int32_t ur = x[base + j].r;                                    \
                int32_t ui = x[base + j].i;                                    \
                x[base + j + half].r = ur - tr;                                \
                x[base + j + half].i = ui - ti_;                               \
                x[base + j].r = ur + tr;                                       \
                x[base + j].i = ui + ti_;                                      \
            }                                                                  \
        }                                                                      \
    } while (0)

static void fft_complex(cpx_q_t *x, int sign)
{
    /* bit reversal permutation */
    for (uint32_t i = 1, j = 0; i < FFT_FIXED_N; i++) {
        uint32_t bit = FFT_FIXED_N >> 1;
        for (; j & bit; bit >>= 1)
            j ^= bit;
        j ^= bit;
        if (i < j) {
            cpx_q_t t = x[i]; x[i] = x[j]; x[j] = t;
        }
    }

    /* butterflies; stage length 2, 4, ..., N */
    for (uint32_t len = 2; len <= FFT_FIXED_N; len <<= 1) {
        uint32_t half = len >> 1;
        uint32_t tstep = FFT_FIXED_N / len; /* twiddle index step */
        if (sign > 0)
            BUTTERFLY_STAGE(1);
        else
            BUTTERFLY_STAGE(0);
    }
}

void fft_real_fwd512(const int32_t *time, cpx_q_t *freq, cpx_q_t *scratch)
{
    /* pack even samples in re, odd samples in im; consumes all of
       time in one copy so the whole input is read before any output
       is written below (time may alias freq) */
    memcpy(scratch, time, FFT_FIXED_N * sizeof(cpx_q_t));

    fft_complex(scratch, -1);

    /*
      Unpack to the 512-point real spectrum, bins 0..256:
        X[0]   = Z0.r + Z0.i          (real)
        X[256] = Z0.r - Z0.i          (real)
        X[k]   = A - j*tw*B,  k = 1..255, with
                 A = (Z[k] + conj(Z[256-k])) / 2
                 B = (Z[k] - conj(Z[256-k])) / 2
                 tw = e^{-j pi k / 256}
      Bins 257..511 are the Hermitian partners of 1..255 and are not
      stored; callers mirror them when needed.
    */
    freq[0].r = scratch[0].r + scratch[0].i;
    freq[0].i = 0;
    freq[256].r = scratch[0].r - scratch[0].i;
    freq[256].i = 0;

    for (int k = 1; k <= 255; k++) {
        int32_t zr = scratch[k].r, zi = scratch[k].i;
        int32_t zcr = scratch[256 - k].r, zci = -scratch[256 - k].i;
        int32_t Ar = zr + zcr, Ai = zi + zci;
        int32_t Br = zr - zcr, Bi = zi - zci;
        /* twiddle e^{-j pi k / 256}: direct for k <= 127, and
           -conj(tw[256-k]) for k >= 128 */
        int32_t wr, wi;
        if (k == 128) {
            wr = 0;
            wi = -2147483647; /* e^{-j pi/2} = -j at full Q31 scale */
        } else if (k <= 127) {
            wr = fft_hw_cos[k];
            wi = fft_hw_sin[k];
        } else {
            wr = -fft_hw_cos[256 - k];
            wi = fft_hw_sin[256 - k];
        }
        int64_t tr = (int64_t)Br * wr - (int64_t)Bi * wi;
        int64_t ti = (int64_t)Br * wi + (int64_t)Bi * wr;
        int32_t cr = (int32_t)(tr >> 31);
        int32_t ci = (int32_t)(ti >> 31);
        /* X[k] = A - j*tw*B with A, B halved: -j*(cr + j*ci) = ci - j*cr */
        freq[k].r = (Ar + ci) >> 1;
        freq[k].i = (Ai - cr) >> 1;
    }
}

void fft_real_inv512(const cpx_q_t *freq, int32_t *time, cpx_q_t *scratch)
{
    /*
      Inverse packing (verified against the direct Hermitian inverse
      DFT).  With X[k+256] = conj(X[256-k]) for k = 1..255 and X[256]
      at Nyquist, the 256-point spectrum of the packed sequence
      g[n] = y[2n] + j*y[2n+1] is

        Zg[k] = G + j * e^{+j 2 pi k / 512} * D

      with G = X[k] + X[k+256] and D = X[k] - X[k+256].  An unscaled
      256-point inverse of Zg yields g directly, so y[2n] = Re g[n]
      and y[2n+1] = Im g[n].
    */
    for (int k = 0; k < FFT_FIXED_N; k++) {
        int32_t xr = freq[k].r, xi = freq[k].i;
        int32_t x2r, x2i;
        if (k == 0) {
            x2r = freq[256].r;
            x2i = freq[256].i;
        } else {
            x2r = freq[256 - k].r;
            x2i = -freq[256 - k].i;
        }
        int32_t Gr = xr + x2r, Gi = xi + x2i;
        int32_t Dr = xr - x2r, Di = xi - x2i;
        /* twiddle e^{+j pi k / 256}: conjugate of the forward table
           entry; for k >= 128 use the k' = 256-k symmetry */
        int32_t wr, wi;
        if (k == 128) {
            wr = 0;
            wi = 2147483647; /* e^{+j pi/2} = +j at full Q31 scale */
        } else if (k <= 127) {
            wr = fft_hw_cos[k];
            wi = -fft_hw_sin[k];
        } else {
            wr = -fft_hw_cos[256 - k];
            wi = -fft_hw_sin[256 - k];
        }
        int64_t tr = (int64_t)Dr * wr - (int64_t)Di * wi;
        int64_t ti = (int64_t)Dr * wi + (int64_t)Di * wr;
        int32_t cr = (int32_t)(tr >> 31);
        int32_t ci = (int32_t)(ti >> 31);
        /* j * (cr + j*ci) = -ci + j*cr */
        scratch[k].r = Gr - ci;
        scratch[k].i = Gi + cr;
    }

    fft_complex(scratch, +1);

    for (int n = 0; n < FFT_FIXED_N; n++) {
        time[2 * n] = scratch[n].r;
        time[2 * n + 1] = scratch[n].i;
    }
}
